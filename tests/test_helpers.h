inline std::filesystem::path temp_dir(const std::string &name) {
    auto base = std::filesystem::temp_directory_path() / ("pe_g1_" + name);
    std::filesystem::create_directories(base);
    return base;
}

inline void write_text(const std::filesystem::path &p, const std::string &text) {
    std::ofstream f(p, std::ios::binary);
    REQUIRE(f.good());
    f << text;
}

inline std::string sha256_of(const std::string &text) {
    return pe::sha256_hex(reinterpret_cast<const uint8_t *>(text.data()), text.size());
}

// Builds a look package directory from LUT text. Returns the manifest sha256.
inline std::string make_look_package(const std::filesystem::path &dir,
                                     const std::string &id,
                                     const std::string &lut_text,
                                     uint32_t dimension) {
    std::filesystem::create_directories(dir);
    const std::string lut_hash = sha256_of(lut_text);
    write_text(dir / "lut.cube", lut_text);
    write_text(dir / "LICENSE.txt", "Test-only package.\n");
    const std::string manifest = R"({
  "schemaVersion": 1,
  "id": ")" + id + R"(",
  "version": "1.0.0",
  "name": ")" + id + R"(",
  "status": "prototype",
  "domain": "srgb-display-v1",
  "sourceKinds": ["cameraRaw"],
  "compatiblePipelines": ["baseline-v0"],
  "amountPolicy": "encoded-domain-linear-blend-v1",
  "operator": {
    "type": "cube3d",
    "opVersion": 1,
    "asset": "lut.cube",
    "assetSha256": ")" + lut_hash + R"(",
    "dimension": )" + std::to_string(dimension) + R"(,
    "interpolation": "trilinear",
    "axisOrder": "red-fastest",
    "domainMin": [0, 0, 0],
    "domainMax": [1, 1, 1]
  },
  "licenseFile": "LICENSE.txt",
  "notes": "generated by the G1 test suite"
})";
    write_text(dir / "manifest.json", manifest);
    return sha256_of(manifest);
}

// Cube file header shared by the generated LUT texts below.
inline std::string cube_header(int n) {
    return "LUT_3D_SIZE " + std::to_string(n) +
           "\nDOMAIN_MIN 0 0 0\nDOMAIN_MAX 1 1 1\n";
}

// 17^3 identity LUT (same content shape as the docs fixture).
inline std::string identity_lut_text(int n = 17) {
    std::string s = "TITLE \"identity test\"\n" + cube_header(n);
    char buf[128];
    for (int b = 0; b < n; b++)
        for (int g = 0; g < n; g++)
            for (int r = 0; r < n; r++) {
                std::snprintf(buf, sizeof(buf), "%.8f %.8f %.8f\n",
                              double(r) / (n - 1), double(g) / (n - 1),
                              double(b) / (n - 1));
                s += buf;
            }
    return s;
}

// Channel-permuted LUT: out(r,g,b) = (g,b,r). Any axis/channel mix-up breaks it.
inline std::string permuted_lut_text(int n = 17) {
    std::string s = cube_header(n);
    char buf[128];
    for (int b = 0; b < n; b++)
        for (int g = 0; g < n; g++)
            for (int r = 0; r < n; r++) {
                std::snprintf(buf, sizeof(buf), "%.8f %.8f %.8f\n",
                              double(g) / (n - 1), double(b) / (n - 1),
                              double(r) / (n - 1));
                s += buf;
            }
    return s;
}

// Red-only ramp LUT: out(r,g,b) = (r, 0, 0). Nice for interpolation checks.
inline std::string red_ramp_lut_text(int n = 17) {
    std::string s = cube_header(n);
    char buf[128];
    for (int b = 0; b < n; b++)
        for (int g = 0; g < n; g++)
            for (int r = 0; r < n; r++) {
                std::snprintf(buf, sizeof(buf), "%.8f 0.00000000 0.00000000\n",
                              double(r) / (n - 1));
                s += buf;
            }
    return s;
}

inline pe::MiniSchemaValidator load_recipe_validator() {
    pe::MiniSchemaValidator v;
    nlohmann::json schema = nlohmann::json::parse(pe::kRecipeSchemaJson, nullptr, false);
    REQUIRE_MESSAGE(schema.is_object(), "embedded recipe schema failed to parse");
    std::string err;
    REQUIRE_MESSAGE(v.load(schema, err), err);
    return v;
}

inline pe::MiniSchemaValidator load_look_validator() {
    pe::MiniSchemaValidator v;
    nlohmann::json schema = nlohmann::json::parse(pe::kLookSchemaJson, nullptr, false);
    REQUIRE_MESSAGE(schema.is_object(), "embedded look schema failed to parse");
    std::string err;
    REQUIRE_MESSAGE(v.load(schema, err), err);
    return v;
}

